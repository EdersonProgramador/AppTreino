import sharp from "sharp";
import path from "node:path";
import fs from "node:fs/promises";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const paymentsDir = path.join(root, "apps/web/public/assets/payments");
const sourceDir = path.join(paymentsDir, "source");
const versionFile = path.join(root, "apps/web/src/components/checkout/payment-assets.version.ts");

const ASSETS = [
  { file: "pix-logo.png", sourceNames: ["pix-logo.png", "pix.png"], liftDarkText: false },
  { file: "card-brands.png", sourceNames: ["card-brands.png", "bandeiras-cartao.png", "bandeiras.png"], liftDarkText: true },
  { file: "trust-badges.png", sourceNames: ["trust-badges.png"], liftDarkText: false }
];

const MIN_TRANSPARENT_RATIO = 0.05;

function isNearBlack(r, g, b, threshold) {
  return r <= threshold && g <= threshold && b <= threshold;
}

function liftDarkForeground(data, channels, threshold = 72) {
  for (let i = 0; i < data.length; i += channels) {
    const alpha = data[i + 3];
    if (alpha < 16) continue;

    const r = data[i];
    const g = data[i + 1];
    const b = data[i + 2];
    const max = Math.max(r, g, b);

    if (max > threshold) continue;

    const lift = 1.85;
    data[i] = Math.min(255, Math.round(r * lift + 58));
    data[i + 1] = Math.min(255, Math.round(g * lift + 58));
    data[i + 2] = Math.min(255, Math.round(b * lift + 58));
  }
}

async function analyzeImage(filePath) {
  const meta = await sharp(filePath).metadata();
  const { data, info } = await sharp(filePath).ensureAlpha().raw().toBuffer({ resolveWithObject: true });

  let transparent = 0;
  for (let i = 3; i < data.length; i += 4) {
    if (data[i] < 16) transparent += 1;
  }

  const total = info.width * info.height;
  return {
    format: meta.format,
    width: meta.width,
    height: meta.height,
    hasAlpha: Boolean(meta.hasAlpha),
    transparentRatio: transparent / total
  };
}

async function removeBlackBackground(inputPath, { bgThreshold = 32, liftDarkText = false } = {}) {
  const { data, info } = await sharp(inputPath).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width, height, channels } = info;
  const visited = new Uint8Array(width * height);
  const queue = [];

  const trySeed = (x, y) => {
    const idx = y * width + x;
    const pi = idx * channels;
    if (visited[idx] || !isNearBlack(data[pi], data[pi + 1], data[pi + 2], bgThreshold)) return;
    queue.push(idx);
  };

  for (let x = 0; x < width; x += 1) {
    trySeed(x, 0);
    trySeed(x, height - 1);
  }
  for (let y = 0; y < height; y += 1) {
    trySeed(0, y);
    trySeed(width - 1, y);
  }

  while (queue.length > 0) {
    const idx = queue.pop();
    if (visited[idx]) continue;
    visited[idx] = 1;

    const pi = idx * channels;
    if (!isNearBlack(data[pi], data[pi + 1], data[pi + 2], bgThreshold)) continue;

    data[pi + 3] = 0;

    const x = idx % width;
    const y = Math.floor(idx / width);
    if (x > 0) queue.push(idx - 1);
    if (x < width - 1) queue.push(idx + 1);
    if (y > 0) queue.push(idx - width);
    if (y < height - 1) queue.push(idx + width);
  }

  if (liftDarkText) {
    liftDarkForeground(data, channels);
  }

  const tempPath = `${inputPath}.tmp.png`;
  await sharp(data, { raw: { width, height, channels } })
    .trim({ threshold: 1 })
    .png({ compressionLevel: 9, adaptiveFiltering: true })
    .toFile(tempPath);

  await fs.rename(tempPath, inputPath);
}

async function copyIfExists(sourcePath, targetPath) {
  try {
    await fs.access(sourcePath);
  } catch {
    return false;
  }

  await fs.copyFile(sourcePath, targetPath);
  return true;
}

async function copyFromSource(sourceNames, targetPath) {
  for (const name of sourceNames) {
    const sourcePath = path.join(sourceDir, name);
    if (await copyIfExists(sourcePath, targetPath)) {
      return name;
    }
  }
  return null;
}

async function writeVersionStamp() {
  const hashes = [];
  for (const asset of ASSETS) {
    const filePath = path.join(paymentsDir, asset.file);
    try {
      const buffer = await fs.readFile(filePath);
      hashes.push(crypto.createHash("sha1").update(buffer).digest("hex").slice(0, 12));
    } catch {
      hashes.push("missing");
    }
  }

  const version = hashes.join("-");
  const contents = `// Generated by scripts/ensure-payment-assets.mjs. Do not edit manually.\nexport const PAYMENT_ASSETS_VERSION = "${version}";\n`;
  await fs.writeFile(versionFile, contents, "utf8");
  return version;
}

await fs.mkdir(sourceDir, { recursive: true });

for (const asset of ASSETS) {
  const targetPath = path.join(paymentsDir, asset.file);
  const syncedFrom = await copyFromSource(asset.sourceNames, targetPath);

  if (syncedFrom) {
    console.log(`[payments] synced source/${syncedFrom} -> ${asset.file}`);
  }

  let stats;
  try {
    stats = await analyzeImage(targetPath);
  } catch (error) {
    console.warn(`[payments] missing ${asset.file}: ${error instanceof Error ? error.message : error}`);
    continue;
  }

  const lostAlpha = stats.format === "jpeg" || stats.transparentRatio < MIN_TRANSPARENT_RATIO;
  if (lostAlpha) {
    console.warn(
      `[payments] ${asset.file} lost transparency (${stats.format}, ${(stats.transparentRatio * 100).toFixed(1)}% alpha). ` +
        "Chat uploads re-encode PNG as JPEG — auto-fixing background."
    );
    await removeBlackBackground(targetPath, { liftDarkText: asset.liftDarkText });
    stats = await analyzeImage(targetPath);
  }

  console.log(
    `[payments] ${asset.file} ok: ${stats.width}x${stats.height}, ${stats.format}, ` +
      `${(stats.transparentRatio * 100).toFixed(1)}% transparent`
  );
}

const version = await writeVersionStamp();
console.log(`[payments] cache version ${version}`);
